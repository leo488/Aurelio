const hash = (s: string) => [...s].reduce((h, c) => (h * 31 + c.charCodeAt(0)) >>> 0, 7)

/** Today's question. The same all day, different the next. */
export const promptFor = (date: string) => PROMPTS[hash(date) % PROMPTS.length]

/** Another question, never the one being shown. */
export function anotherPrompt(current: string) {
  let p = current
  while (p === current) p = PROMPTS[Math.floor(Math.random() * PROMPTS.length)]
  return p
}
